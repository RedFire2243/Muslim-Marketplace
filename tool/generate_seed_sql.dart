// Generates supabase/seed.sql from the same fictional data the demo uses.
//
//   dart run tool/generate_seed_sql.dart > supabase/seed.sql
//
// Timestamps are written relative to now() so a freshly seeded database
// looks current. The accounts are fictional and use a shared password meant
// only for local development; never run this seed against production.
// ignore_for_file: avoid_print

import 'dart:convert';

import 'package:muslim_marketplace/src/data/seed/seed_data.dart';
import 'package:muslim_marketplace/src/domain/listing.dart';

const localPassword = 'community-demo-2026';

void main() {
  final reference = DateTime.utc(2026, 10, 24, 12);
  final s = SeedData.build(reference);

  String q(String? v) => v == null ? 'null' : "'${v.replaceAll("'", "''")}'";
  String arr(List<String> v) =>
      v.isEmpty ? "'{}'::text[]" : 'array[${v.map(q).join(', ')}]::text[]';
  String ts(DateTime? t) {
    if (t == null) return 'null';
    final secs = reference.difference(t).inSeconds;
    return "now() - interval '$secs seconds'";
  }

  String b(bool v) => v ? 'true' : 'false';

  final out = StringBuffer()
    ..writeln(
      '-- Generated by tool/generate_seed_sql.dart. Do not edit by hand.',
    )
    ..writeln('-- Fictional sample data for LOCAL DEVELOPMENT ONLY.')
    ..writeln('-- Every account below uses the password "$localPassword".')
    ..writeln()
    ..writeln('begin;')
    ..writeln();

  out.writeln(
    '-- Accounts (the signup trigger creates profiles and settings).',
  );
  for (final p in s.profiles) {
    final email = SeedData.emailFor(p);
    final meta = jsonEncode({'display_name': p.displayName});
    out.writeln('''
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change, email_change_token_new, email_change_token_current,
  phone_change, phone_change_token, reauthentication_token)
values ('00000000-0000-0000-0000-000000000000', ${q(p.id)}, 'authenticated', 'authenticated', ${q(email)},
  extensions.crypt(${q(localPassword)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}'::jsonb, ${q(meta)}::jsonb, ${ts(p.createdAt)}, ${ts(p.updatedAt)},
  '', '', '', '', '', '', '', '');
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (${q(p.id)}, ${q(p.id)}, ${q(p.id)},
  jsonb_build_object('sub', ${q(p.id)}, 'email', ${q(email)}, 'email_verified', true),
  'email', now(), now(), now());''');
  }

  out.writeln();
  out.writeln('-- Profiles and private settings.');
  for (final p in s.profiles) {
    out.writeln('''
update public.profiles set
  display_name = ${q(p.displayName)}, headline = ${q(p.headline)},
  skills = ${arr(p.skills)}, interests = ${arr(p.interests)},
  offering_summary = ${q(p.offeringSummary)}, seeking_summary = ${q(p.seekingSummary)},
  area_id = ${q(p.areaId)}, open_to_remote = ${b(p.openToRemote)},
  community_affiliation = ${q(p.communityAffiliation)}, linkedin_url = ${q(p.linkedinUrl)},
  directory_visible = ${b(p.directoryVisible)}, is_sample = true,
  created_at = ${ts(p.createdAt)}
where id = ${q(p.id)};
update public.profile_settings set
  goals = ${q(jsonEncode([for (final g in p.goals) g.toJson()]))}::jsonb,
  personalization_enabled = ${b(p.personalizationEnabled)}, onboarding_complete = true
where id = ${q(p.id)};''');
  }

  out.writeln();
  out.writeln('-- Listings.');
  for (final Listing l in s.listings) {
    out.writeln(
      '''
insert into public.listings (id, owner_id, title, description, listing_type, direction, category, tags,
  area_id, remote_available, compensation_type, compensation_details, status, is_sample, created_at, updated_at, closed_at)
values (${q(l.id)}, ${q(l.ownerId)}, ${q(l.title)}, ${q(l.description)}, ${q(l.type.wire)}, ${q(l.direction.wire)},
  ${q(l.category.wire)}, ${arr(l.tags)}, ${q(l.areaId)}, ${b(l.remoteAvailable)}, ${q(l.compensationType?.wire)},
  ${q(l.compensationDetails)}, ${q(l.status.wire)}, true, ${ts(l.createdAt)}, ${ts(l.updatedAt)}, ${ts(l.closedAt)});''',
    );
  }

  out.writeln();
  out.writeln('-- Saved listings.');
  for (final x in s.saved) {
    out.writeln(
      'insert into public.saved_listings (user_id, listing_id, saved_at) values (${q(x.userId)}, ${q(x.listingId)}, ${ts(x.savedAt)});',
    );
  }

  out.writeln();
  out.writeln('-- Connection requests.');
  for (final r in s.requests) {
    out.writeln(
      '''
insert into public.connection_requests (id, sender_id, recipient_id, kind, listing_id, listing_title, message, status, created_at, responded_at)
values (${q(r.id)}, ${q(r.senderId)}, ${q(r.recipientId)}, ${q(r.listingId == null ? 'introduction' : 'listing')},
  ${q(r.listingId)}, ${q(r.listingTitle)}, ${q(r.message)}, ${q(r.status.wire)}, ${ts(r.createdAt)}, ${ts(r.respondedAt)});''',
    );
  }

  out.writeln();
  out.writeln('-- Conversations and messages.');
  for (final c in s.conversations) {
    out.writeln('''
insert into public.conversations (id, request_id, participant_a, participant_b, listing_id, listing_title, created_at)
values (${q(c.id)}, ${q(c.requestId)}, ${q(c.participantIds[0])}, ${q(c.participantIds[1])}, ${q(c.listingId)},
  ${q(c.listingTitle)}, ${ts(c.createdAt)});''');
  }
  for (final m in s.messages) {
    out.writeln(
      '''
insert into public.messages (id, conversation_id, sender_id, body, client_id, created_at)
values (${q(m.id)}, ${q(m.conversationId)}, ${q(m.senderId)}, ${q(m.body)}, ${q(m.clientId)}, ${ts(m.createdAt)});''',
    );
  }

  out.writeln();
  out.writeln('-- Recommendation feedback events.');
  for (final e in s.events) {
    out.writeln('''
insert into public.recommendation_events (id, user_id, listing_id, event_type, listing_type, category, tags, created_at)
values (${q(e.id)}, ${q(e.userId)}, ${q(e.listingId)}, ${q(e.type.wire)}, ${q(e.listingType.wire)}, ${q(e.category.wire)},
  ${arr(e.tags)}, ${ts(e.createdAt)});''');
  }

  out
    ..writeln()
    ..writeln('commit;');
  print(out.toString());
}
